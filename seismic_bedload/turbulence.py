import numpy as np
from scipy.special import gamma
from typing import Optional, Union
from seismic_bedload.abc_class import Turbulence
from seismic_bedload.models import SedimentParams, SeismicParams


class TurbulenceModel(Turbulence):
    """
    Turbulence model: PSD generated by turbulent flow in a river
    (Gimbert et al., 2014).

    The model predicts ground velocity PSD from hydraulic and sediment
    parameters without invoking bedload particle impacts — it captures
    the seismic signature of the flow itself.
    """

    # Model constants (Gimbert et al. 2014 / Lamb et al. 2008)
    K: float = 0.5       # von Kármán-related prefactor
    C: float = 0.5       # empirical constant
    X1r: float = None    # roughness sublayer reference height; set to ks/2 in _psd
    N11: float = 0.6     # horizontal coupling coefficient
    N12: float = 0.8     # horizontal coupling coefficient
    alpha1: float = 0.12  # from Lamb et al. 2008
    alpha2: float = 0.2

    def __init__(
        self,
        sediment_params: Optional[SedimentParams] = None,
        seismic_params: Optional[SeismicParams] = None,
    ):
        self.sediment_params = sediment_params or SedimentParams()
        self.seismic_params = seismic_params or SeismicParams()

    def calculate_seismic_properties(
        self, f: np.ndarray, r0: float
    ) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
        """Return phase velocity vc, group velocity vu, and attenuation chi."""
        sp = self.seismic_params
        vc = sp.vc0 * (f / sp.f0) ** (-sp.zeta)
        vu = vc / (1 + sp.zeta)
        beta = (
            2 * np.pi * r0 * (1 + sp.zeta)
            * f ** (1 + sp.zeta - sp.eta)
            / (sp.vc0 * sp.Q0 * sp.f0 ** (sp.zeta - sp.eta))
        )
        chi = (
            2 * np.log(1 + 1 / beta) * np.exp(-2 * beta)
            + (1 - np.exp(-beta)) * np.exp(-beta) * np.sqrt(2 * np.pi / beta)
        )
        return vc, vu, chi

    # Grain-size modulation  Phi(D)
    # currently not used in forward_psd, but implemented here for potential use in future extensions
    def _grain_size_filter(
        self,
        f: Union[float, np.ndarray],
        D: np.ndarray,
        D50: float,
        H: float,
        pdf: Optional[np.ndarray] = None,
        Dstd: float = 0.52,
    ) -> float:
        """
        Compute the grain-size modulation integral phi_D.

        Parameters
        ----------
        f     : frequency (scalar or array); when scalar, ki_fl is 1-D over D.
        D     : grain diameter array [m]
        D50   : median grain size [m]
        H     : flow depth [m]
        pdf   : grain-size probability density (must integrate to ~1 over D).
                If None, uses the raised-cosine distribution with width Dstd.
        Dstd  : log-space width parameter for raised-cosine PDF (default 0.52).
        """
        if pdf is None:
            s = Dstd / np.sqrt(1 / 3 - 2 / np.pi**2)
            pdf = (
                (1 / (2 * s))
                * (1 + np.cos(np.pi * (np.log(D) - np.log(D50)) / s))
                / D
            )
            # zero outside the support
            mask = np.abs(np.log(D) - np.log(D50)) > s
            pdf = np.where(mask, 0.0, pdf)

        ks = 3 * D50
        u_star = np.sqrt(self.sediment_params.g * H * np.sin(np.arctan(1.0)))
        # fc is the corner frequency per grain size (scalar f version handled below)
        X1r_val = ks / 2
        cu_X1r = (X1r_val / (self.alpha1 * ks)) * (1 - X1r_val / (2 * ks) * ks / H)

        fc = cu_X1r * u_star / D  # shape: (len(D),)

        # ki_fl shape depends on f:
        # scalar f → (len(D),); array f → broadcast handled by caller
        ki_fl = 1.0 / (1.0 + (2.0 * np.asarray(f)[..., np.newaxis] / fc) ** (4 / 3))
        # ki_fl: (..., len(D))
        # integrate over D: phi_D has shape (...)
        phi_D = np.trapezoid(pdf * D**2 * ki_fl**2, D, axis=-1)
        return phi_D

